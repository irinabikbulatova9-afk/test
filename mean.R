#!/usr/bin/env Rscript

# Получаем аргументы, указанные после имени скрипта в командной строке.
# Например, команда `Rscript mean.R 5 10 15` передаст строки "5", "10" и "15".
args <- commandArgs(trailingOnly = TRUE)

# Если пользователь не передал числа, используем демонстрационный набор.
if (length(args) == 0) {
  values <- c(10, 20, 30, 40, 50)

  # message() выводит пояснение отдельно от основного результата программы.
  message("Числа не переданы; используется пример: ", paste(values, collapse = ", "))
} else {
  # Аргументы командной строки являются текстом, поэтому преобразуем их в числа.
  # suppressWarnings() скрывает стандартное предупреждение: ошибку объясним ниже.
  values <- suppressWarnings(as.numeric(args))

  # Некорректная строка после преобразования становится NA.
  # В таком случае завершаем программу с понятным сообщением.
  if (anyNA(values)) {
    stop("Все аргументы должны быть числами. Пример: Rscript mean.R 10 20 30", call. = FALSE)
  }
}

# Вычисляем арифметическое среднее всех чисел.
result <- mean(values)

# Форматируем и выводим итог без научной записи и лишних пробелов.
cat(sprintf("Среднее: %s\n", format(result, trim = TRUE, scientific = FALSE)))
