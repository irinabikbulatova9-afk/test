#!/usr/bin/env Rscript

# Получаем два ряда чисел из аргументов командной строки.
# Пример: Rscript correlation.R "1,2,3" "2,4,6"
args <- commandArgs(trailingOnly = TRUE)

# Преобразует строку с числами через запятую в числовой вектор.
parse_series <- function(text, series_name) {
  parts <- trimws(strsplit(text, ",", fixed = TRUE)[[1]])
  values <- suppressWarnings(as.numeric(parts))

  # Пустые элементы и нечисловые значения после преобразования становятся NA.
  if (length(parts) == 0 || any(parts == "") || anyNA(values)) {
    stop(
      sprintf("Ряд %s должен содержать только числа через запятую.", series_name),
      call. = FALSE
    )
  }

  values
}

# Без аргументов запускаем программу на демонстрационных данных.
if (length(args) == 0) {
  x <- c(1, 2, 3, 4, 5)
  y <- c(2, 4, 5, 8, 10)
  message("Ряды не переданы; используются демонстрационные данные.")
} else {
  # Для корреляции нужны ровно два ряда наблюдений.
  if (length(args) != 2) {
    stop(
      "Передайте два ряда чисел. Пример: Rscript correlation.R \"1,2,3\" \"2,4,6\"",
      call. = FALSE
    )
  }

  x <- parse_series(args[1], "X")
  y <- parse_series(args[2], "Y")
}

# Наблюдения сопоставляются попарно, поэтому длины рядов должны совпадать.
if (length(x) != length(y)) {
  stop("Ряды X и Y должны иметь одинаковую длину.", call. = FALSE)
}

# Для вычисления корреляции необходимо минимум две пары наблюдений.
if (length(x) < 2) {
  stop("В каждом ряду должно быть не менее двух чисел.", call. = FALSE)
}

# Корреляция не определена, если все значения одного из рядов одинаковы.
if (sd(x) == 0 || sd(y) == 0) {
  stop("Корреляция не определена для ряда без разброса значений.", call. = FALSE)
}

# По умолчанию cor() вычисляет коэффициент корреляции Пирсона.
result <- cor(x, y, method = "pearson")

# Выводим результат с точностью до шести знаков после запятой.
cat(sprintf("Корреляция Пирсона: %.6f\n", result))
